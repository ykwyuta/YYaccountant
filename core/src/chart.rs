pub fn accounts(kind: BookKind) -> Vec<Account> {
    let list = match kind {
        BookKind::Household => HOUSEHOLD,
        BookKind::SoleProprietor => BUSINESS,
    };
    list.iter()
        .enumerate()
        .map(|(i, t)| Account {
            id: i as i64 + 1,
            code: t.code.into(),
            name: t.name.into(),
            category: t.category,
            role: t.role,
            parent: None,
            payment: t.payment,
            guide: t.guide.into(),
            keywords: t
                .keywords
                .split(',')
                .filter(|s| !s.is_empty())
                .map(String::from)
                .collect(),
            archived: false,
        })
        .collect()
}
pub fn distinctions(kind: BookKind) -> &'static [Distinction] {
    match kind {
        BookKind::Household => HOUSEHOLD_DISTINCTIONS,
        BookKind::SoleProprietor => BUSINESS_DISTINCTIONS,
    }
}

#[derive(Clone, Debug, Serialize)]
pub struct Suggestion {
    pub account: i64,
    pub code: String,
    pub name: String,
    pub category: Category,
    pub score: u32,
    pub matched: Vec<String>,
    pub guide: String,
}
#[derive(Clone, Debug, Serialize)]
pub struct GuideResult {
    pub suggestions: Vec<Suggestion>,
    pub distinctions: Vec<DistinctionView>,
}
#[derive(Clone, Debug, Serialize)]
pub struct DistinctionView {
    pub title: &'static str,
    pub accounts: Vec<(i64, String)>,
    pub explanation: &'static str,
    pub examples: Vec<(String, Option<i64>, String)>,
}

fn normalize(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            'Ａ'..='Ｚ' | 'ａ'..='ｚ' | '０'..='９' => {
                char::from_u32(c as u32 - 0xFEE0).unwrap_or(c)
            }
            c => c,
        })
        .flat_map(char::to_lowercase)
        .collect()
}

/// Ranks accounts for a free text description and lists the distinctions involving them.
pub fn guide(book: &Book, query: &str, account: Option<i64>) -> GuideResult {
    let q = normalize(query);
    let words: Vec<&str> = q.split_whitespace().collect();
    let mut suggestions = vec![];
    for a in book.accounts.iter().filter(|a| !a.archived) {
        let mut score = 0;
        let mut matched = vec![];
        for w in &words {
            let name = normalize(&a.name);
            if name.contains(w) || w.contains(name.as_str()) {
                score += 10;
                matched.push(a.name.clone());
            }
            for k in &a.keywords {
                let k2 = normalize(k);
                if k2.contains(w) || (w.chars().count() >= 2 && w.contains(k2.as_str())) {
                    score += 6;
                    matched.push(k.clone());
                }
            }
            if normalize(&a.guide).contains(w) {
                score += 2;
            }
            if a.code == *w {
                score += 10;
            }
        }
        for dist in distinctions(book.kind) {
            for (example, code) in dist.examples {
                if *code == a.code && words.iter().any(|w| normalize(example).contains(w)) {
                    score += 4;
                    matched.push((*example).to_string());
                }
            }
        }
        if score > 0 || Some(a.id) == account {
            matched.sort();
            matched.dedup();
            suggestions.push(Suggestion {
                account: a.id,
                code: a.code.clone(),
                name: a.name.clone(),
                category: a.category,
                score,
                matched,
                guide: a.guide.clone(),
            });
        }
    }
    suggestions.sort_by(|a, b| b.score.cmp(&a.score).then(a.code.cmp(&b.code)));
    suggestions.truncate(12);
    let codes: Vec<String> = if words.is_empty() && account.is_none() {
        vec![]
    } else {
        suggestions.iter().take(5).map(|s| s.code.clone()).collect()
    };
    let by_code = |c: &str| book.accounts.iter().find(|a| a.code == c);
    let distinctions = distinctions(book.kind)
        .iter()
        .filter(|d| {
            (words.is_empty() && account.is_none())
                || d.codes.iter().any(|c| codes.iter().any(|x| x == c))
        })
        .map(|d| DistinctionView {
            title: d.title,
            accounts: d
                .codes
                .iter()
                .filter_map(|c| by_code(c).map(|a| (a.id, a.name.clone())))
                .collect(),
            explanation: d.explanation,
            examples: d
                .examples
                .iter()
                .map(|(e, c)| {
                    let a = by_code(c);
                    (
                        (*e).to_string(),
                        a.map(|a| a.id),
                        a.map(|a| a.name.clone())
                            .unwrap_or_else(|| (*c).to_string()),
                    )
                })
                .collect(),
        })
        .collect();
    GuideResult {
        suggestions,
        distinctions,
    }
}

/// User documentation of both charts, generated so that it never drifts from the guides.
pub fn markdown() -> String {
    let mut out = String::from(
        "# 勘定科目の選び方\n\n<!-- core/src/chart.rs から生成。直接編集せず `YYA_UPDATE_DOCS=1 cargo test -p yy-accountant --test docs` で更新します。 -->\n\n帳簿を作ると、種類に応じた次の科目表が登録されます。どの科目にも使い分けの説明があり、アプリの「かんたん入力」「勘定科目・取引先 › 使い分けガイド」やMCPの `account_guide` で、内容の言葉（例: ガソリン、住民税）から候補を探せます。説明は一般的な記帳の考え方で、税額や特例の判断は最新の制度と専門家の助言で確認してください。\n",
    );
    for kind in BookKind::ALL {
        out += &format!(
            "\n## {}の帳簿\n\n### 迷いやすい科目の使い分け\n",
            kind.label()
        );
        let list = accounts(kind);
        let name = |c: &str| {
            list.iter()
                .find(|a| a.code == c)
                .map(|a| a.name.clone())
                .unwrap_or_default()
        };
        for d in distinctions(kind) {
            out += &format!(
                "\n#### {}\n\n{}\n\n| 例 | 選ぶ科目 |\n|---|---|\n",
                d.title, d.explanation
            );
            for (example, code) in d.examples {
                out += &format!("| {example} | {code} {} |\n", name(code));
            }
        }
        out += "\n### 科目一覧\n";
        for category in Category::ALL {
            out += &format!(
                "\n#### {}\n\n| コード | 科目 | 使い分け | 検索語 |\n|---|---|---|---|\n",
                category.label()
            );
            for a in list.iter().filter(|a| a.category == category) {
                out += &format!(
                    "| {} | {}{} | {} | {} |\n",
                    a.code,
                    a.name,
                    a.role
                        .map(|r| format!("（役割: {}）", r.label()))
                        .unwrap_or_default(),
                    a.guide.replace('|', "｜"),
                    a.keywords.join("、")
                );
            }
        }
    }
    out
}

