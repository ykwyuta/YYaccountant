/// `docs/user/tutorial.md` の内容。
pub fn markdown() -> String {
    let mut out = String::from(
        "# チュートリアル：家計簿・税金・ライフプラン\n\n\
         会計や税金の知識がなくても使い始められるように、画面の操作と考え方を順に説明します。\
         同じ内容はアプリの「はじめに」（Web UI）とヘルプメニューの「チュートリアル」（ネイティブ画面）でも読めます。\
         この文書は `core/src/tutorial.rs` から生成しています。\n\n\
         > 税制の金額基準や期限は毎年のように変わります。税額は試算として使い、申告前に国税庁・市区町村の案内で確かめてください。\n",
    );
    for c in CHAPTERS {
        out += &format!("\n## {}\n\n{}\n", c.title, c.lead);
        for s in c.steps {
            out += &format!("\n### {}\n\n", s.title);
            for p in s.body {
                out += &format!("{p}\n\n");
            }
            if !s.try_it.is_empty() {
                out += &format!("やってみる（画面: {}）\n\n", s.screen);
                for (i, t) in s.try_it.iter().enumerate() {
                    out += &format!("{}. {t}\n", i + 1);
                }
                out += "\n";
            }
        }
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// プレーンテキスト（ネイティブ画面の読み取り専用欄）。
pub fn text() -> String {
    let mut out = String::new();
    for c in CHAPTERS {
        out += &format!("■ {}\r\n{}\r\n\r\n", c.title, c.lead);
        for s in c.steps {
            out += &format!("● {}\r\n", s.title);
            for p in s.body {
                out += &format!("{p}\r\n");
            }
            for (i, t) in s.try_it.iter().enumerate() {
                out += &format!("  やってみる{}（{}）: {t}\r\n", i + 1, s.screen);
            }
            out += "\r\n";
        }
    }
    out
}
